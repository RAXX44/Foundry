'use client';

import { useEffect, useState } from 'react';
import { useRouter } from 'next/navigation';
import Editor from '@monaco-editor/react';
import { Download, ArrowLeft, Copy, Check } from 'lucide-react';

interface GeneratedCode {
  prismaSchema: string;
  apiRoutes: string;
  mermaidDiagram: string;
}

export default function ResultsPage() {
  const router = useRouter();
  const [code, setCode] = useState<GeneratedCode>({
    prismaSchema: '',
    apiRoutes: '',
    mermaidDiagram: '',
  });
  const [activeTab, setActiveTab] = useState<'schema' | 'routes' | 'setup'>('schema');
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    // Load results from sessionStorage
    const resultsStr = sessionStorage.getItem('erdResults');
    if (!resultsStr) {
      router.push('/');
      return;
    }

    try {
      const results = JSON.parse(resultsStr);
      setCode({
        prismaSchema: results.prismaSchema || '// Schema will be generated here',
        apiRoutes: results.apiRoutes || '// API routes will be generated here',
        mermaidDiagram: results.mermaidDiagram || '',
      });
    } catch (error) {
      console.error('Failed to parse results:', error);
      router.push('/');
    }
  }, [router]);

  const handleCopy = async () => {
    const textToCopy = activeTab === 'schema' ? code.prismaSchema : code.apiRoutes;
    await navigator.clipboard.writeText(textToCopy);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const content = activeTab === 'schema' ? code.prismaSchema : code.apiRoutes;
    const filename = activeTab === 'schema' ? 'schema.prisma' : 'routes.ts';
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadAll = async () => {
    const JSZip = (await import('jszip')).default;
    const zip = new JSZip();

    // Extract model names from prisma schema
    const modelNames = code.prismaSchema
      .match(/model\s+(\w+)\s*\{/g)
      ?.map(m => m.replace(/model\s+/, '').replace(/\s*\{/, ''))
      ?? [];

    // Generate dynamic API endpoints list
    const endpointsList = modelNames
      .map(m => `- GET /api/${m.toLowerCase()} - Get all ${m}\n- POST /api/${m.toLowerCase()} - Create ${m}\n- PUT /api/${m.toLowerCase()}/[id] - Update ${m}\n- DELETE /api/${m.toLowerCase()}/[id] - Delete ${m}`)
      .join('\n');

    // Generate dynamic README
    const readme = `# Generated by Foundry 🔥
Powered by IBM watsonx.ai

## 📦 Generated Models
${modelNames.map(m => `- ${m}`).join('\n')}

## 🚀 Setup Steps
\`\`\`bash
# 1. Install dependencies
npm install prisma @prisma/client

# 2. Copy schema.prisma to your prisma/ folder

# 3. Setup environment
echo 'DATABASE_URL="postgresql://user:password@localhost:5432/mydb"' > .env

# 4. Run migration
npx prisma migrate dev --name init

# 5. Generate client
npx prisma generate
\`\`\`

## 🛣️ Your API Endpoints
${endpointsList}

## 📁 Files Included
- schema.prisma - Your Prisma database schema
- routes.ts - Next.js API routes with full CRUD
- README.md - This setup guide
- .gitignore - Git ignore patterns
- .env.example - Environment variable template
- types.ts - TypeScript interfaces
- app/api/health/route.ts - Health check endpoint
- Dockerfile - Docker container configuration
- docker-compose.yml - Docker Compose setup

Generated with Foundry - ERD to Code Generator`;

    zip.file('schema.prisma', code.prismaSchema);
    zip.file('routes.ts', code.apiRoutes);
    zip.file('README.md', readme);

    zip.file('.gitignore', `node_modules/
.env
.env.local
.env*.local
.DS_Store
dist/
.next/
*.log`);

    zip.file('.env.example', `# Database Connection
DATABASE_URL="postgresql://user:password@localhost:5432/mydb"
# MySQL: DATABASE_URL="mysql://user:password@localhost:3306/mydb"
# SQLite: DATABASE_URL="file:./dev.db"`);

    zip.file('types.ts', `// Auto-generated by Foundry
// TypeScript interfaces for your models

${modelNames.map(m => `export interface ${m} {
  id: number;
  createdAt: Date;
  updatedAt: Date;
}`).join('\n\n')}`);

    zip.file('app/api/health/route.ts', `import { NextResponse } from 'next/server';

export async function GET() {
  return NextResponse.json({
    status: 'healthy',
    timestamp: new Date().toISOString(),
    service: 'Foundry Generated API',
    models: ${JSON.stringify(modelNames)},
  });
}`);

    zip.file('Dockerfile', `FROM node:18-alpine
WORKDIR /app
COPY package*.json ./
RUN npm install
COPY . .
RUN npx prisma generate
RUN npm run build
EXPOSE 3000
CMD ["npm", "start"]`);

    zip.file('docker-compose.yml', `version: '3.8'
services:
  app:
    build: .
    ports:
      - "3000:3000"
    environment:
      - DATABASE_URL=postgresql://postgres:password@db:5432/mydb
    depends_on:
      - db
  db:
    image: postgres:15
    environment:
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: password
      POSTGRES_DB: mydb
    ports:
      - "5432:5432"
    volumes:
      - postgres_data:/var/lib/postgresql/data
volumes:
  postgres_data:`);

    const content = await zip.generateAsync({ type: 'blob' });
    const url = URL.createObjectURL(content);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'foundry-generated.zip';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  // Extract model names for success banner
  const modelNames = code.prismaSchema
    .match(/model\s+(\w+)\s*\{/g)
    ?.map(m => m.replace(/model\s+/, '').replace(/\s*\{/, ''))
    ?? [];

  return (
    <main className="min-h-screen bg-gradient-to-br from-gray-900 via-gray-800 to-gray-900">
      {/* Header */}
      <header className="border-b border-gray-800 bg-gray-900/50 backdrop-blur-sm">
        <div className="container mx-auto px-4 py-6">
          <div className="flex items-center justify-between">
            <button
              onClick={() => router.push('/')}
              className="flex items-center gap-2 text-gray-400 hover:text-white transition-colors"
            >
              <ArrowLeft className="w-5 h-5" />
              <span>Back to Upload</span>
            </button>
            <h1 className="text-xl font-bold text-white">Generated Code</h1>
            <div className="w-32" /> {/* Spacer for centering */}
          </div>
        </div>
      </header>

      {/* Main Content */}
      <div className="container mx-auto px-4 py-6 h-[calc(100vh-80px)]">
        {/* Success Banner */}
        {code.prismaSchema && (
          <div className="mb-4 p-3 bg-green-500/10 border border-green-500/30 rounded-lg flex items-center gap-2">
            <span className="text-green-400">✅</span>
            <span className="text-green-400 text-sm font-medium">
              Code generated successfully! {modelNames.length} models detected: {modelNames.join(', ')}
            </span>
          </div>
        )}
        <div className="grid md:grid-cols-2 gap-6 h-full">
          {/* Prisma Schema Editor */}
          <div className="flex flex-col bg-gray-800/50 backdrop-blur-sm rounded-xl border border-gray-700 overflow-hidden">
            <div className="flex items-center justify-between px-4 py-3 border-b border-gray-700">
              <div className="flex items-center gap-2">
                <button
                  onClick={() => setActiveTab('schema')}
                  className={`px-4 py-2 rounded-lg text-sm font-medium transition-colors ${
                    activeTab === 'schema'
                      ? 'bg-blue-500 text-white'
                      : 'text-gray-400 hover:text-white'
                  }`}
                >
                  schema.prisma
                </button>
                <button
                  onClick={() => setActiveTab('routes')}
                  className={`px-4 py-2 rounded-lg text-sm font-medium transition-colors ${
                    activeTab === 'routes'
                      ? 'bg-blue-500 text-white'
                      : 'text-gray-400 hover:text-white'
                  }`}
                >
                  API Routes
                </button>
                <button
                  onClick={() => setActiveTab('setup')}
                  className={`px-4 py-2 rounded-lg text-sm font-medium transition-colors ${
                    activeTab === 'setup'
                      ? 'bg-blue-500 text-white'
                      : 'text-gray-400 hover:text-white'
                  }`}
                >
                  Setup Guide
                </button>
              </div>
              <div className="flex items-center gap-2">
                <button
                  onClick={handleCopy}
                  className="p-2 text-gray-400 hover:text-white transition-colors rounded-lg hover:bg-gray-700"
                  title="Copy to clipboard"
                >
                  {copied ? (
                    <Check className="w-5 h-5 text-green-400" />
                  ) : (
                    <Copy className="w-5 h-5" />
                  )}
                </button>
                <button
                  onClick={handleDownload}
                  className="p-2 text-gray-400 hover:text-white transition-colors rounded-lg hover:bg-gray-700"
                  title="Download file"
                >
                  <Download className="w-5 h-5" />
                </button>
              </div>
            </div>
            <div className="flex-1 overflow-hidden">
              {activeTab === 'setup' ? (
                <div className="p-6 space-y-6 overflow-auto h-full text-sm">
                  <div>
                    <h3 className="text-green-400 font-bold mb-2">Step 1: Install Dependencies</h3>
                    <div className="bg-gray-900 rounded-lg p-4 font-mono text-gray-300">
                      npm install prisma @prisma/client
                    </div>
                  </div>
                  <div>
                    <h3 className="text-green-400 font-bold mb-2">Step 2: Setup Database</h3>
                    <div className="bg-gray-900 rounded-lg p-4 font-mono text-gray-300">
                      npx prisma migrate dev --name init
                    </div>
                  </div>
                  <div>
                    <h3 className="text-green-400 font-bold mb-2">Step 3: Generate Client</h3>
                    <div className="bg-gray-900 rounded-lg p-4 font-mono text-gray-300">
                      npx prisma generate
                    </div>
                  </div>
                  <div>
                    <h3 className="text-green-400 font-bold mb-2">Step 4: Use in your code</h3>
                    <div className="bg-gray-900 rounded-lg p-4 font-mono text-gray-300 space-y-1">
                      <p className="text-gray-500">{"// Import Prisma Client"}</p>
                      <p>{"import { PrismaClient } from '@prisma/client'"}</p>
                      <p>{"const prisma = new PrismaClient()"}</p>
                      <p className="mt-2 text-gray-500">{"// Example usage"}</p>
                      <p>{"const data = await prisma.yourModel.findMany()"}</p>
                    </div>
                  </div>
                  <div>
                    <h3 className="text-green-400 font-bold mb-2">Step 5: Add to .env</h3>
                    <div className="bg-gray-900 rounded-lg p-4 font-mono text-gray-300">
                      DATABASE_URL="postgresql://user:password@localhost:5432/mydb"
                    </div>
                  </div>
                </div>
              ) : (
                <Editor
                  height="100%"
                  language={activeTab === 'schema' ? 'prisma' : 'typescript'}
                  value={activeTab === 'schema' ? code.prismaSchema : code.apiRoutes}
                  theme="vs-dark"
                  options={{
                    readOnly: false,
                    minimap: { enabled: false },
                    fontSize: 14,
                    lineNumbers: 'on',
                    scrollBeyondLastLine: false,
                    automaticLayout: true,
                    tabSize: 2,
                  }}
                  onChange={(value) => {
                    if (activeTab === 'schema') {
                      setCode({ ...code, prismaSchema: value || '' });
                    } else {
                      setCode({ ...code, apiRoutes: value || '' });
                    }
                  }}
                />
              )}
            </div>
          </div>

          {/* Second Editor (Mirror) */}
          <div className="flex flex-col bg-gray-800/50 backdrop-blur-sm rounded-xl border border-gray-700 overflow-hidden">
            <div className="flex items-center justify-between px-4 py-3 border-b border-gray-700">
              <div className="flex items-center gap-2">
                <span className="text-sm font-medium text-gray-400">
                  {activeTab === 'schema' ? 'API Routes Preview' : 'Schema Preview'}
                </span>
              </div>
              <div className="flex items-center gap-2">
                <button
                  onClick={async () => {
                    const textToCopy = activeTab === 'schema' ? code.apiRoutes : code.prismaSchema;
                    await navigator.clipboard.writeText(textToCopy);
                    setCopied(true);
                    setTimeout(() => setCopied(false), 2000);
                  }}
                  className="p-2 text-gray-400 hover:text-white transition-colors rounded-lg hover:bg-gray-700"
                  title="Copy to clipboard"
                >
                  {copied ? (
                    <Check className="w-5 h-5 text-green-400" />
                  ) : (
                    <Copy className="w-5 h-5" />
                  )}
                </button>
                <button
                  onClick={() => {
                    const content = activeTab === 'schema' ? code.apiRoutes : code.prismaSchema;
                    const filename = activeTab === 'schema' ? 'routes.ts' : 'schema.prisma';
                    const blob = new Blob([content], { type: 'text/plain' });
                    const url = URL.createObjectURL(blob);
                    const a = document.createElement('a');
                    a.href = url;
                    a.download = filename;
                    a.click();
                    URL.revokeObjectURL(url);
                  }}
                  className="p-2 text-gray-400 hover:text-white transition-colors rounded-lg hover:bg-gray-700"
                  title="Download file"
                >
                  <Download className="w-5 h-5" />
                </button>
              </div>
            </div>
            <div className="flex-1 overflow-hidden">
              <Editor
                height="100%"
                language={activeTab === 'schema' ? 'typescript' : 'prisma'}
                value={activeTab === 'schema' ? code.apiRoutes : code.prismaSchema}
                theme="vs-dark"
                options={{
                  readOnly: false,
                  minimap: { enabled: false },
                  fontSize: 14,
                  lineNumbers: 'on',
                  scrollBeyondLastLine: false,
                  automaticLayout: true,
                  tabSize: 2,
                }}
                onChange={(value) => {
                  if (activeTab === 'schema') {
                    setCode({ ...code, apiRoutes: value || '' });
                  } else {
                    setCode({ ...code, prismaSchema: value || '' });
                  }
                }}
              />
            </div>
          </div>
        </div>

        {/* Mermaid Diagram Section */}
        <div className="mt-10 bg-gray-800/50 backdrop-blur-sm rounded-xl border border-gray-700 p-6">
          <h3 className="text-xl font-bold text-white mb-4 flex items-center gap-2">
            <span>🔮</span>
            <span>Live ERD Diagram {modelNames.length > 0 ? `(${modelNames.length} models detected)` : ''}</span>
          </h3>
          <div className="flex justify-center bg-white p-6 rounded-xl overflow-auto max-h-[700px] w-full">
            {code.mermaidDiagram ? (
              <img
                src={`https://mermaid.ink/img/${btoa(code.mermaidDiagram)}`}
                alt="Generated ERD"
                className="max-w-full h-auto"
                onError={(e) => {
                  e.currentTarget.style.display = 'none';
                  e.currentTarget.nextElementSibling?.classList.remove('hidden');
                }}
              />
            ) : null}
            <p className={`text-gray-500 ${code.mermaidDiagram ? 'hidden' : ''}`}>
              No diagram available.
            </p>
          </div>
        </div>

        {/* Action Buttons */}
        <div className="mt-10 mb-16 space-y-4">
          {/* Primary Actions */}
          <div className="flex justify-center gap-6">
            <button
              onClick={handleDownloadAll}
              className="px-10 py-4 bg-gradient-to-r from-blue-500 to-purple-600 text-white rounded-xl font-semibold text-base hover:from-blue-600 hover:to-purple-700 transition-all shadow-lg hover:shadow-xl flex items-center gap-3"
            >
              <span>📦</span> Download All Files (.zip)
            </button>
            <button
              onClick={() => router.push('/')}
              className="px-10 py-4 bg-gray-700 text-white rounded-xl font-semibold text-base hover:bg-gray-600 transition-colors flex items-center gap-3"
            >
              <span>🔄</span> Generate Another
            </button>
          </div>
          {/* Coming Soon */}
          <div className="flex justify-center gap-4 pb-8">
            <button disabled className="px-6 py-2.5 bg-gray-800/50 text-gray-500 rounded-lg text-sm border border-gray-700/50 cursor-not-allowed flex items-center gap-2">
              🚀 Deploy to Neon <span className="text-xs bg-gray-700/80 px-2 py-0.5 rounded-full">Coming Soon</span>
            </button>
            <button disabled className="px-6 py-2.5 bg-gray-800/50 text-gray-500 rounded-lg text-sm border border-gray-700/50 cursor-not-allowed flex items-center gap-2">
              🐙 Push to GitHub <span className="text-xs bg-gray-700/80 px-2 py-0.5 rounded-full">Coming Soon</span>
            </button>
            <button disabled className="px-6 py-2.5 bg-gray-800/50 text-gray-500 rounded-lg text-sm border border-gray-700/50 cursor-not-allowed flex items-center gap-2">
              🐳 Docker Deploy <span className="text-xs bg-gray-700/80 px-2 py-0.5 rounded-full">Coming Soon</span>
            </button>
          </div>
        </div>
      </div>
    </main>
  );
}

